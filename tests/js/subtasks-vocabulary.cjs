const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const s=fs.readFileSync('src/convest/subtasks/static/app.js','utf8');
const labels=['pickup','harvest','return','adjust','pickup','harvest','return'];
const context={state:{mode:'coarse',selected:{coarse:6},coarseLabels:{return:'放回番茄'},stages:{coarse:{segments:labels.map(label=>({label}))}}},copy:v=>JSON.parse(JSON.stringify(v))};vm.createContext(context);
vm.runInContext(s.slice(s.indexOf('const vocabulary='),s.indexOf('function stageColor(')),context);
assert.equal(context.englishLabel('return'),'Right hand returns the held object to the right plate');
assert.equal(context.bilingualLabel('return'),'3. 放回番茄 · Right hand returns the held object to the right plate');
const doc={stage:'coarse',note:'中文',projection:{policy:'nearest',review_events:[{note:'中文'}]},segments:labels.map((label,i)=>({label,start_frame:i,end_frame:i+1,text:'中文',reviewed:true}))};
const out=context.englishDocument(doc);
assert.equal(out.segments[2].text,'Right hand returns the held object to the right plate');
assert.equal(out.segments[6].text,'Right hand returns the held object to the right plate');
assert(!/[\u4e00-\u9fff]/.test(JSON.stringify(out)));
assert.equal(doc.segments[0].text,'中文');
assert.equal(out.segments[6].segment_index,7);
console.log('subtasks bilingual UI: numbering English export shared return and nonmutation passed');
const airborne={...doc,source:{remote_source:{dataset:'/mnt/data/train_platform/datasets/tomato_sharpa/normal/full-block-more/A/1112_820_1014_normal'}},segments:[{label:'adjust',start_frame:0,end_frame:1,reviewed:false}]};
const airborneOut=context.englishDocument(airborne);
assert.equal(airborneOut.prompt_profile,'tomato-in-hand-five-phases-v1');
assert.equal(airborneOut.segments[0].text,'Right hand reorients the held tomato truss in the air');
context.state.stages.coarse.source=airborne.source;
assert.equal(context.bilingualLabel('adjust'),'4. 空中调整番茄 · Right hand reorients the held tomato truss in the air');
assert.equal(airborneOut.segments[0].reviewed,false);
console.log('in air adjustment UI and export are scoped to new workflow');
